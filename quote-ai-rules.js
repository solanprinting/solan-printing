/* ═══════════════════════════════════════════════════════════════════════════
   quote-ai-rules.js — הוראות-תמחור שהבעלים כותב, לתוך הפרומפט של תמחור ה-AI.

   ⚠️ **הבקשה (בעלים, 2026-08-10): "אפשר להכניס לו הוראות לתמחור?"** —
   למשל שישאל על פלאיירים אם הם נכנסים לבד להדפסה או בשילוב, כי המחיר שונה.

   ⚠️ **הפתרון אינו לקודד את החוק הזה.** חוקי-תמחור הם ידע-עסקי שמשתנה,
   והם של בעל-הדפוס ולא שלי; חוק שמקודד בפרומפט דורש פריסה כדי לשנות
   פסיק. לכן ההוראות הן **שדה טקסט שהבעלים עורך**, נשמר עם המחירון
   ומסונכרן איתו — והחוק שביקש הוא רק ברירת-המחדל הראשונה.

   ⚠️ **קדימות מוצהרת.** הוראות-הבעלים גוברות על כללי-העבודה המובנים —
   אחרת חוק שסותר ברירת-מחדל היה נבלע בשקט, והמשתמש היה מקבל תמחור
   שמתעלם ממה שכתב בלי לדעת למה. הן מוזרקות **בסוף** הפרומפט ומסומנות
   במפורש כגוברות.

   ⚠️ מה שהן **אינן** גוברות עליו: החשבון עצמו (טונאז', אלפים, לוחות)
   מגיע מהתעריפון. חוק-עסקי משנה מה שואלים ואיך מתמחרים; הוא לא הופך
   כפל לחיבור.

   הרצת הבדיקות: node quote-ai-rules-tests.js
   ═══════════════════════════════════════════════════════════════════════════ */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.QuoteAiRules = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  /* ── ברירת-המחדל: החוק שהבעלים תיאר ─────────────────────────────────────
     ⚠️ שילוב-בגיליון (gang run) אינו הנחה שרירותית — הוא משנה את **מספר
     הגיליונות שהעבודה נושאת**, וזה הבסיס לכל התמחור (נייר · הדפסה ·
     לוחות). לכן זו שאלה שחייבת להישאל לפני החישוב, לא אחריו.

     ⚠️ ומחיר-בשילוב מותנה במציאת שותף. הצעה שניתנה כמשולבת ולא נמצא
     שותף היא הפסד — ולכן החוק מחייב לומר זאת בהצעה. */
  var DEFAULT_RULES = [
    'פלאיירים ומוצרים שטוחים — לבד או בשילוב:',
    'שאל תמיד "העבודה נכנסת לבד לגיליון או בשילוב עם עבודה אחרת?"',
    '[[אפשרויות: לבד | בשילוב]]',
    '- לבד: העבודה נושאת את הגיליון כולו — נייר, הדפסה ולוחות מלאים.',
    '- בשילוב: שאל איזה חלק מהגיליון היא תופסת (חצי / רבע / אחר),',
    '  וחשב נייר, הדפסה ולוחות לפי החלק הזה בלבד.',
    '- בהצעה משולבת ציין במפורש שהמחיר מותנה בשילוב עם עבודה נוספת,',
    '  ושבלעדיו המחיר הוא של הדפסה לבד.'
  ].join('\n');

  function clean(s) { return String(s == null ? '' : s).trim(); }

  /* ── בניית הקטע לפרומפט ────────────────────────────────────────────────
     ⚠️ מחזיר מחרוזת ריקה כשאין הוראות — כותרת של סעיף ריק מלמדת את
     המודל שיש חוקים ואין, וזו הזמנה להמצאה. */
  function rulesBlock(rules) {
    var r = clean(rules);
    if (!r) return '';
    return '\n\n━━━ הוראות-תמחור של בית-הדפוס ━━━\n'
      + '⚠️ ההוראות הבאות נכתבו על-ידי בעל בית-הדפוס והן **גוברות** על כללי\n'
      + 'העבודה שלמעלה בכל מקום שבו יש סתירה. אל תתעלם מהן ואל תרכך אותן.\n'
      + 'הן אינן משנות את חישוב התעריפון עצמו (טונאז\', אלפים, לוחות) —\n'
      + 'הן קובעות מה לשאול, מתי, ואיך המחיר משתנה בהתאם.\n'
      + 'אם הוראה דורשת נתון שחסר — שאל עליו לפני שאתה מציג מחיר.\n\n'
      + r;
  }

  /* ⚠️ שמירה שאינה מוחקת: טופס שנפתח בלי השדה (DOM ישן במטמון) היה
     שומר מחרוזת ריקה ומוחק את כל ההוראות. הערך הקיים נשמר כשאין קלט. */
  function mergeRules(formValue, current) {
    if (formValue === undefined || formValue === null) return clean(current);
    return clean(formValue);
  }

  /* עוזר לממשק: האם ההוראות הן עדיין ברירת-המחדל שלא נגעו בה. */
  function isDefault(rules) { return clean(rules) === clean(DEFAULT_RULES); }

  return { DEFAULT_RULES: DEFAULT_RULES, rulesBlock: rulesBlock,
           mergeRules: mergeRules, isDefault: isDefault };
});
